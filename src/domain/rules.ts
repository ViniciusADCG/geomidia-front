export function getRequiredRadius(mediaType: MediaType, areaM2: number, rules: MediaRule[] = []): number {
  const managedRule = rules.find((rule) => rule.media_type === mediaType && rule.is_active);
  if (managedRule) {
    if (
      managedRule.area_threshold_m2 != null
      && managedRule.radius_above_threshold_meters != null
      && areaM2 > managedRule.area_threshold_m2
    ) {
      return managedRule.radius_above_threshold_meters;
    }
    return managedRule.base_radius_meters;
  }
  if (mediaType === 'painel de led') return areaM2 > 5 ? 1000 : 250;
  if (mediaType === 'painel eletronico modular' || mediaType === 'empena de led') return 1000;
  return 80;
}

export function mediaTypeLabel(mediaType: MediaType): string {
  return MEDIA_TYPE_OPTIONS.find((item) => item.value === mediaType)?.title ?? mediaType;
}

export function mediaTypeColor(mediaType: MediaType): string {
  const colors: Record<MediaType, string> = {
    outdoor: '#2f80ed',
    'front light': '#219653',
    triface: '#7b61ff',
    'painel de led': '#f2994a',
    'painel eletronico modular': '#ef6c00',
    empena: '#d9468f',
    'empena de led': '#0e9f9a',
  };
  return colors[mediaType];
}

export function statusColor(status: MediaStatus): string {
  if (status === 'aprovado') return 'success';
  if (status === 'irregular' || status === 'vencido') return 'error';
  if (status === 'cartografia' || status === 'jurídico') return 'primary';
  return 'warning';
}

export function statusLabel(status: MediaStatus): string {
  return STATUS_OPTIONS.find((item) => item.value === status)?.title ?? status;
}
