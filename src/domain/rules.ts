export function mediaTypeOptionsFromRules(rules: MediaRule[]): Array<{ title: string; value: MediaType }> {
  if (rules.length === 0) return MEDIA_TYPE_OPTIONS;

  const activeRules = new Map(
    rules
      .filter((rule) => rule.is_active)
      .map((rule) => [rule.media_type, rule]),
  );

  return MEDIA_TYPE_OPTIONS
    .filter((option) => activeRules.has(option.value))
    .map((option) => ({
      title: activeRules.get(option.value)?.name.trim() || option.title,
      value: option.value,
    }));
}

